static int fail(const char *what) {
  fprintf(stderr, "freetype: %s\n", what);
  return 1;
}

static int is_test_font(FT_Face face) {
  return face->num_glyphs == 2 && face->family_name != NULL &&
         strcmp(face->family_name, "CabinProbe") == 0 &&
         FT_Get_Char_Index(face, 'A') == 1;
}

/* Opens the face a gzip or bzip2 stream decompresses from `data`. */
static FT_Error open_compressed(FT_Library library, FT_Memory memory,
                                const unsigned char *data, unsigned long size,
                                int bzip2, FT_Face *face) {
  static FT_StreamRec source, stream;
  FT_Open_Args args;
  FT_Error error;

  memset(&source, 0, sizeof source);
  memset(&stream, 0, sizeof stream);
  source.base = (unsigned char *)data;
  source.size = size;
  source.memory = memory;
  error = bzip2 ? FT_Stream_OpenBzip2(&stream, &source)
                : FT_Stream_OpenGzip(&stream, &source);
  if (error) return error;
  memset(&args, 0, sizeof args);
  args.flags = FT_OPEN_STREAM;
  args.stream = &stream;
  /* The face closes the stream when it is done. */
  return FT_Open_Face(library, &args, 0, face);
}

int main(void) {
  /* BGRA of the PNG's red, green, blue and white pixels. */
  static const unsigned char kPixels[2][8] = {
      {0, 0, 255, 255, 0, 255, 0, 255},
      {255, 0, 0, 255, 255, 255, 255, 255},
  };
  FT_Library library;
  FT_Face face;
  FT_Memory memory;
  FT_Bitmap *bitmap;
  FT_Int major, minor, patch;
  unsigned int row, col;

  if (FT_Init_FreeType(&library)) return fail("init");
  FT_Library_Version(library, &major, &minor, &patch);
  if (major != 2 || minor != 15 || patch != 0) return fail("version");

  /* WOFF2 decoding goes through brotli, the sbix PNG through libpng. */
  if (FT_New_Memory_Face(library, kWoff2, sizeof kWoff2, 0, &face))
    return fail("open WOFF2 face");
  if (!is_test_font(face) || !FT_HAS_COLOR(face) || !FT_HAS_SBIX(face))
    return fail("WOFF2 face contents");
  memory = face->memory;
  if (FT_Set_Pixel_Sizes(face, 0, 16) ||
      FT_Load_Char(face, 'A', FT_LOAD_COLOR))
    return fail("load color glyph");
  bitmap = &face->glyph->bitmap;
  if (face->glyph->format != FT_GLYPH_FORMAT_BITMAP ||
      bitmap->pixel_mode != FT_PIXEL_MODE_BGRA || bitmap->width != 2 ||
      bitmap->rows != 2)
    return fail("color glyph bitmap");
  for (row = 0; row < 2; ++row)
    if (memcmp(bitmap->buffer + row * bitmap->pitch, kPixels[row], 8) != 0)
      return fail("color glyph pixels");
  FT_Done_Face(face);

  if (FT_New_Memory_Face(library, kWoff2, sizeof kWoff2 / 2, 0, &face) == 0)
    return fail("truncated WOFF2 accepted");

  /* The gzip stream inflates through zlib. */
  if (open_compressed(library, memory, kTtfGz, sizeof kTtfGz, 0, &face))
    return fail("open gzip face");
  if (!is_test_font(face) || !FT_IS_SCALABLE(face))
    return fail("gzip face contents");
  /* The outline rasterizes to a fully covered 8x8 square at 10 ppem. */
  if (FT_Set_Pixel_Sizes(face, 0, 10) ||
      FT_Load_Char(face, 'A', FT_LOAD_NO_HINTING | FT_LOAD_RENDER))
    return fail("render outline");
  bitmap = &face->glyph->bitmap;
  if (bitmap->pixel_mode != FT_PIXEL_MODE_GRAY || bitmap->width != 8 ||
      bitmap->rows != 8)
    return fail("outline bitmap size");
  for (row = 0; row < 8; ++row)
    for (col = 0; col < 8; ++col)
      if (bitmap->buffer[row * bitmap->pitch + col] != 255)
        return fail("outline coverage");
  FT_Done_Face(face);

  /* The bzip2 stream decompresses through bzip2. */
  if (open_compressed(library, memory, kTtfBz2, sizeof kTtfBz2, 1, &face))
    return fail("open bzip2 face");
  if (!is_test_font(face)) return fail("bzip2 face contents");
  FT_Done_Face(face);

  FT_Done_FreeType(library);
  return 0;
}
