/* Validates cose-wg/Examples mac0-tests/HMac-01.json (public domain, the
 * Unlicense) with the openssl port's OpenSSL 4.1.0; the system copies CI
 * checks with are 3.x. */
#include <cose/cose.h>

#include <openssl/crypto.h>

#include <stdio.h>

static const byte key[32] = {
    0x84, 0x9b, 0x57, 0x21, 0x9d, 0xae, 0x48, 0xde, 0x64, 0x6d, 0x07,
    0xdb, 0xb5, 0x33, 0x56, 0x6e, 0x97, 0x66, 0x86, 0x45, 0x7c, 0x14,
    0x91, 0xbe, 0x3a, 0x76, 0xdc, 0xea, 0x6c, 0x42, 0x71, 0x88};

static const byte mac0[] = {
    0xd1, 0x84, 0x43, 0xa1, 0x01, 0x05, 0xa0, 0x54, 0x54, 0x68, 0x69, 0x73,
    0x20, 0x69, 0x73, 0x20, 0x74, 0x68, 0x65, 0x20, 0x63, 0x6f, 0x6e, 0x74,
    0x65, 0x6e, 0x74, 0x2e, 0x58, 0x20, 0xa1, 0xa8, 0x48, 0xd3, 0x47, 0x1f,
    0x9d, 0x61, 0xee, 0x49, 0x01, 0x8d, 0x24, 0x4c, 0x82, 0x47, 0x72, 0xf2,
    0x23, 0xad, 0x4f, 0x93, 0x52, 0x93, 0xf1, 0x78, 0x9f, 0xc3, 0xa0, 0x8d,
    0x8c, 0x58};

int main(void) {
  cose_errback err;
  int type = 0;
  HCOSE_MAC0 h = (HCOSE_MAC0)COSE_Decode(mac0, sizeof mac0, &type,
                                         COSE_mac0_object, &err);
  int ok = h != NULL && COSE_Mac0_validate(h, key, sizeof key, &err);
  if (h != NULL) {
    COSE_Mac0_Free(h);
  }
  printf("OpenSSL %s\n", OpenSSL_version(OPENSSL_VERSION));
  if (!ok || OPENSSL_version_major() != 4 || OPENSSL_version_minor() != 1) {
    fputs("FAIL: HMac-01 did not validate with the openssl port's 4.1.0\n",
          stderr);
    return 1;
  }
  puts("cose-c: HMac-01 validates with the openssl port's OpenSSL 4.1.0");
  return 0;
}
