#define CHECK(cond)                                                    \
  do {                                                                 \
    if (!(cond)) {                                                     \
      std::fprintf(stderr, "%s:%d: CHECK(%s) failed\n", __FILE__, __LINE__, #cond); \
      return EXIT_FAILURE;                                             \
    }                                                                  \
  } while (0)

static size_t Append(void* out, const uint8_t* buf, size_t len) {
  std::vector<uint8_t>* v = static_cast<std::vector<uint8_t>*>(out);
  v->insert(v->end(), buf, buf + len);
  return len;
}

int main() {
  brunsli::JPEGData jpg;
  CHECK(brunsli::ReadJpeg(kJpeg, sizeof(kJpeg), brunsli::JPEG_READ_ALL, &jpg));
  CHECK(jpg.width == 16 && jpg.height == 16);

  size_t len = brunsli::GetMaximumBrunsliEncodedSize(jpg);
  std::vector<uint8_t> brn(len);
  CHECK(brunsli::BrunsliEncodeJpeg(jpg, brn.data(), &len));
  CHECK(len > 6 && len < sizeof(kJpeg));
  brn.resize(len);

  // The brunsli signature.
  static const uint8_t kSignature[] = {0x0a, 0x04, 'B', 0xd2, 0xd5, 'N'};
  for (size_t i = 0; i < sizeof(kSignature); ++i) CHECK(brn[i] == kSignature[i]);
  CHECK(brunsli::IsBrunsli(brn.data(), brn.size()));

  // Decoding reproduces the original JPEG byte for byte.
  brunsli::JPEGData decoded;
  CHECK(brunsli::BrunsliDecodeJpeg(brn.data(), brn.size(), &decoded) ==
        brunsli::BRUNSLI_OK);
  std::vector<uint8_t> out;
  CHECK(brunsli::WriteJpeg(decoded, brunsli::JPEGOutput(Append, &out)));
  CHECK(out.size() == sizeof(kJpeg));
  for (size_t i = 0; i < out.size(); ++i) CHECK(out[i] == kJpeg[i]);

  // Malformed and truncated input is rejected.
  static const uint8_t kGarbage[] = {'n', 'o', 't', ' ', 'b', 'r', 'u', 'n', 's', 'l', 'i'};
  CHECK(!brunsli::IsBrunsli(kGarbage, sizeof(kGarbage)));
  brunsli::JPEGData bad;
  CHECK(brunsli::BrunsliDecodeJpeg(kGarbage, sizeof(kGarbage), &bad) !=
        brunsli::BRUNSLI_OK);
  brunsli::JPEGData truncated;
  CHECK(brunsli::BrunsliDecodeJpeg(brn.data(), brn.size() / 2, &truncated) !=
        brunsli::BRUNSLI_OK);
  return EXIT_SUCCESS;
}
